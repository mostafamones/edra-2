// Rasterizes the small Hugeicons set to template PNGs (@1x/@2x/@3x, black on transparent).
// Stroke width stays at the upstream 1.5. Rerun after changing ICONS: npm run sync:icons
import { writeFileSync, readFileSync, mkdirSync } from "node:fs";
import { createRequire } from "node:module";
import { Resvg } from "@resvg/resvg-js";
import * as icons from "@hugeicons/core-free-icons";

const ICONS = {
  sessions: "Calendar03Icon",
  assessments: "FileEditIcon",
  academy: "School01Icon",
  students: "UserGroupIcon",
  scan: "CenterFocusIcon",
  search: "Search01Icon",
  check: "Tick02Icon",
  add: "Add01Icon",
  close: "Cancel01Icon",
  back: "ArrowLeft01Icon",
  "sign-out": "Logout03Icon",
  "circle-check": "CheckmarkCircle02Icon",
  circle: "CircleIcon",
};
const POINTS = 24;
const out = new URL("../assets/icons/", import.meta.url);
mkdirSync(out, { recursive: true });

const attr = (k) => k.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
for (const [file, name] of Object.entries(ICONS)) {
  const nodes = icons[name];
  if (!nodes) throw new Error(`Missing Hugeicon ${name}`);
  const body = nodes
    .map(([tag, { key, ...a }]) => `<${tag} ${Object.entries(a).map(([k, v]) => `${attr(k)}="${v}"`).join(" ")}/>`)
    .join("");
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" color="#000">${body}</svg>`;
  for (const scale of [1, 2, 3]) {
    const png = new Resvg(svg, { fitTo: { mode: "width", value: POINTS * scale } }).render().asPng();
    writeFileSync(new URL(`${file}${scale === 1 ? "" : `@${scale}x`}.png`, out), png);
  }
}

const pkg = JSON.parse(readFileSync(createRequire(import.meta.url).resolve("@hugeicons/core-free-icons/package.json"), "utf8"));
writeFileSync(
  new URL("ATTRIBUTION.md", out),
  `Icons: Hugeicons free (stroke rounded) v${pkg.version}, ${pkg.license} License, https://hugeicons.com\n` +
    `Generated by scripts/sync-hugeicons.mjs at stroke width 1.5. Do not edit by hand.\n\n` +
    Object.entries(ICONS).map(([f, n]) => `- ${f}.png: ${n}`).join("\n") + "\n",
);
