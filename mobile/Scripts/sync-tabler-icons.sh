#!/bin/zsh
# Copies the Tabler outline icons the app uses into the asset catalog as template vector images.
# Source: @tabler/icons (MIT, https://github.com/tabler/tabler-icons), taken from ../web/node_modules.
# Usage: Scripts/sync-tabler-icons.sh   (re-run after adding a name below)
set -euo pipefail
cd "$(dirname "$0")/.."

SRC=../web/node_modules/@tabler/icons
DEST=EdraInstructor/Resources/Assets.xcassets/Icons
ICONS=(calendar-clock file-pencil building-community book school microscope code palette music trophy world selector check logout plus scan clock bolt bolt-off dots user-x users circle circle-check x chevron-left chevron-right)

VERSION=$(python3 -c "import json;print(json.load(open('$SRC/package.json'))['version'])")
rm -rf "$DEST"; mkdir -p "$DEST"
echo '{ "info" : { "author" : "xcode", "version" : 1 }, "properties" : { "provides-namespace" : false } }' > "$DEST/Contents.json"

for name in $ICONS; do
  set="$DEST/tabler-$name.imageset"; mkdir -p "$set"
  # Asset catalogs don't resolve currentColor; template rendering re-tints the black strokes.
  sed 's/currentColor/#000000/' "$SRC/icons/outline/$name.svg" > "$set/$name.svg"
  cat > "$set/Contents.json" <<JSON
{
  "images" : [ { "filename" : "$name.svg", "idiom" : "universal" } ],
  "info" : { "author" : "xcode", "version" : 1 },
  "properties" : { "preserves-vector-representation" : true, "template-rendering-intent" : "template" }
}
JSON
done
cat > "$DEST/ATTRIBUTION.md" <<MD
Icons: Tabler Icons (outline) v$VERSION, MIT License, https://github.com/tabler/tabler-icons
Generated by Scripts/sync-tabler-icons.sh. Do not edit by hand.
MD
echo "Synced ${#ICONS} icons (Tabler v$VERSION)."
