#!/usr/bin/env node
// Converts the Hugeicons the app uses into the asset catalog as template vector images (stroke width 1.5).
// Source: @hugeicons/core-free-icons (MIT, https://github.com/hugeicons/hugeicons-react), taken from ../web/node_modules.
// The Tabler→Hugeicons choices mirror web/src/components/shared/icons.tsx so both apps show the same glyphs.
// Usage: node Scripts/sync-hugeicons.mjs   (re-run after adding a name below; set HUGEICONS_DIR to use another install)
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const src = resolve(process.env.HUGEICONS_DIR ?? join(root, "../web/node_modules/@hugeicons/core-free-icons"));
const dest = join(root, "EdraInstructor/Resources/Assets.xcassets/Icons");
const ICONS = [
  "Add01Icon", "BookOpen01Icon", "CalendarClockIcon", "Cancel01Icon", "CheckmarkCircle02Icon", "ChevronLeftIcon",
  "ChevronRightIcon", "CircleIcon", "Clock01Icon", "CodeIcon", "FileEditIcon", "FlashIcon", "FlashOffIcon", "Globe02Icon",
  "GraduationCapIcon", "Logout01Icon", "MicroscopeIcon", "MoreHorizontalIcon", "MusicNote01Icon", "PaintBoardIcon",
  "ScanIcon", "School01Icon", "Search01Icon", "Tick02Icon", "TrophyIcon", "UserAdd01Icon", "UserXIcon", "UsersIcon",
];

const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, "$1-$2").replace(/([A-Za-z])(\d)/g, "$1-$2").toLowerCase();
const version = JSON.parse(readFileSync(join(src, "package.json"), "utf8")).version;

rmSync(dest, { recursive: true, force: true });
mkdirSync(dest, { recursive: true });
writeFileSync(join(dest, "Contents.json"), '{ "info" : { "author" : "xcode", "version" : 1 }, "properties" : { "provides-namespace" : false } }\n');

for (const name of ICONS) {
  const { default: nodes } = await import(pathToFileURL(join(src, "dist/esm", `${name}.js`)).href);
  const slug = kebab(name.replace(/Icon$/, ""));
  const body = nodes.map(([tag, attrs]) => {
    const out = Object.entries(attrs).filter(([k]) => k !== "key").map(([k, v]) => {
      // Asset catalogs don't resolve currentColor; template rendering re-tints black. Force 1.5 like the web adapter.
      const value = k === "strokeWidth" ? "1.5" : String(v).replace("currentColor", "#000000");
      return `${kebab(k)}="${value}"`;
    });
    return `  <${tag} ${out.join(" ")} />`;
  });
  if (!body.some((line) => line.includes('stroke-width="1.5"'))) throw new Error(`${name} has no stroked element`);
  const set = join(dest, `hugeicons-${slug}.imageset`);
  mkdirSync(set);
  writeFileSync(join(set, `${slug}.svg`),
    `<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none">\n${body.join("\n")}\n</svg>\n`);
  writeFileSync(join(set, "Contents.json"), `{
  "images" : [ { "filename" : "${slug}.svg", "idiom" : "universal" } ],
  "info" : { "author" : "xcode", "version" : 1 },
  "properties" : { "preserves-vector-representation" : true, "template-rendering-intent" : "template" }
}
`);
}

writeFileSync(join(dest, "ATTRIBUTION.md"), `Icons: Hugeicons Free (@hugeicons/core-free-icons) v${version}, stroke width 1.5, MIT License, https://hugeicons.com
Generated by Scripts/sync-hugeicons.mjs. Do not edit by hand.
`);
console.log(`Synced ${ICONS.length} icons (Hugeicons v${version}).`);
